from pylatexenc.latexencode import utf8tolatex
from bust._version import __VERSION__
from bust.enums import RegisterType


class Documentation(object):
    """Class for auto-generation of module documentation"""

    def __init__(self, module):
        self.module = module

    def return_tex_documentation(self, test_version=None):
        """Generate LaTeX documentation for the module."""
        if test_version is None:
            version = __VERSION__
        else:
            version = test_version

        # Build the LaTeX document using f-strings
        result = tex_top
        result += f"\n\n\\title{{{utf8tolatex(self.module.name)}}}\n"
        result += "\\author{Version: 1.0}\n"
        result += "\\date{\\today\\ \\currenttime}\n\n"
        result += "\\pagestyle{fancy}\n"
        result += "\\fancyhf{}\n"
        result += f"\\fancyhead[C]{{Generated by bust {version}}}\n"
        result += "\\fancyfoot[L]{\\today\\ \\currenttime}\n"
        result += "\\fancyfoot[C]{\\thepage}\n"
        result += "\\fancyfoot[R]{Version: 1.0}\n\n\n"
        result += "\\begin{document}\n\n"
        result += "\\maketitle\n"
        result += "\\thispagestyle{fancy}\n\n"
        result += f"{utf8tolatex(self.module.description)}\n\n"
        result += "\\section{Register List}\n\n"
        result += tex_table_top

        for i, reg in enumerate(self.module.registers):
            reset_val = int(reg.reset, 16) if isinstance(reg.reset, str) else reg.reset
            result += f"\n      {i} & {utf8tolatex(reg.name)} & {reg.mode.value.upper()}{reg.return_stall_string()} & \\texttt{{0x{reg.address:08X}}} & {reg.type.value.upper()} & {reg.width} & \\texttt{{0x{reset_val:X}}} \\\\\n"
            result += "      \\hline"

        result += "\n" + tex_table_bot
        result += "\n\n\\section{Registers}\n\n"

        for reg in self.module.registers:
            # Register header
            reg_name = utf8tolatex(reg.name)
            reg_mode = reg.mode.value.upper()
            pulse_info = (
                f" for {reg.pulse_cycles} cycles "
                if reg.mode.value.lower() == "pulse"
                else ""
            )
            stall_info = f" - STALL for {reg.stall_cycles} cycles" if reg.stall else ""

            result += f"\\begin{{register}}{{H}}{{{reg_name} - {reg_mode}{pulse_info}{stall_info}}}{{0x{reg.address:08X}}}"
            result += f"  \\par {utf8tolatex(reg.description)} \\regnewline\n"
            result += f"  \\label{{{reg.name}}}\n"

            # Handle register fields
            if reg.type != RegisterType.FIELDS:
                # Simple register (non-fields)
                if reg.width < self.module.data_width:
                    result += f"  \\regfield{{unused}}{{{self.module.data_width - reg.width}}}{{{reg.width}}}{{-}}\n"
                reset_val = (
                    int(reg.reset, 16) if isinstance(reg.reset, str) else reg.reset
                )
                if reg.width == 1:
                    result += f"  \\regfield{{}}{{{reg.width}}}{{0}}{{{reset_val}}}\n"
                else:
                    result += (
                        f"  \\regfield{{}}{{{reg.width}}}{{0}}{{{{0x{reset_val:X}}}}}\n"
                    )
            else:
                # Fields register - need to process from highest bit to lowest
                sorted_fields = sorted(
                    reg.fields, key=lambda f: f.pos_low, reverse=True
                )

                # Add unused space at the top if needed
                highest_field = (
                    max(reg.fields, key=lambda f: f.pos_high) if reg.fields else None
                )
                if (
                    highest_field
                    and highest_field.pos_high + 1 < self.module.data_width
                ):
                    unused_width = self.module.data_width - highest_field.pos_high - 1
                    unused_pos = highest_field.pos_high + 1
                    result += f"  \\regfield{{unused}}{{{unused_width}}}{{{unused_pos}}}{{-}}\n"

                # Add fields in reverse order (high to low)
                for j, field in enumerate(sorted_fields):
                    field_reset = (
                        int(field.reset, 16)
                        if isinstance(field.reset, str)
                        else field.reset
                    )
                    if field.width == 1:
                        result += f"  \\regfield{{{field.name}}}{{{field.width}}}{{{field.pos_low}}}{{{field_reset}}}\n"
                    else:
                        result += f"  \\regfield{{{field.name}}}{{{field.width}}}{{{field.pos_low}}}{{{{0x{field_reset:X}}}}}\n"

                    # Add unused space between fields
                    if j < len(sorted_fields) - 1:
                        next_field = sorted_fields[j + 1]
                        if field.pos_low > next_field.pos_high + 1:
                            unused_width = field.pos_low - next_field.pos_high - 1
                            unused_pos = next_field.pos_high + 1
                            result += f"  \\regfield{{unused}}{{{unused_width}}}{{{unused_pos}}}{{-}}\n"

                # Add unused space before lowest field if needed
                lowest_field = (
                    min(reg.fields, key=lambda f: f.pos_low) if reg.fields else None
                )
                if lowest_field and lowest_field.pos_low > 0:
                    result += (
                        f"  \\regfield{{unused}}{{{lowest_field.pos_low}}}{{0}}{{-}}\n"
                    )

            result += "\\reglabel{Reset}\\regnewline\n"

            # Add field descriptions for FIELDS registers
            if reg.type == RegisterType.FIELDS and reg.fields:
                result += "  \\begin{regdesc}\\begin{reglist}[field0]\n"
                for field in reg.fields:
                    result += (
                        f"    \\item [{field.name}] {utf8tolatex(field.description)}"
                    )
                result += "  \\end{reglist}\\end{regdesc}\n"

            result += "\\end{register}\n\n"

        result += "\\end{document}\n"
        return result


tex_top = r"""\documentclass{article}
\usepackage{fancyhdr}
\usepackage{datetime}
\usepackage[margin=1in]{geometry}
\usepackage{register}
\usepackage{enumitem}
\setlist[description]{leftmargin=\parindent,labelindent=\parindent}
\usepackage{calc}
\usepackage{tabularx}

\usepackage{listings}
\lstdefinelanguage{VHDL}{
   morekeywords=[1]{
     library,use,all,entity,is,port,in,out,end,architecture,of,
     begin,and,others
   },
   morecomment=[l]--
}

\lstdefinestyle{vhdl}{
   language     = VHDL,
   basicstyle   = \ttfamily,
}"""


tex_table_top = r"""\begin{table}[h!]
  \begin{center}
    \label{tab:table1}
    \begin{tabularx}{\linewidth}{|l|X|l|l|l|c|l|}
      \hline
      \textbf{\#} & \textbf{Name} & \textbf{Mode} & \textbf{Address} & \textbf{Type} & \textbf{Width} &
      \textbf{Reset} \\
      \hline"""

tex_table_bot = r"""    \end{tabularx}
  \end{center}
\end{table}"""
