#!/usr/bin/env bash
# Check that an installed bust (not the source tree) works: it reports the
# expected version and regenerates the committed example outputs.
# Usage: scripts/smoke-test.sh <expected-version>
set -euo pipefail

expected_version="$1"
examples="$(cd "$(dirname "$0")/../example" && pwd)"
output_dir="$(mktemp -d)"
# bust writes debug.log to the working directory.
cd "$output_dir"

bust --version | grep -Fx "bust $expected_version"
for example in example_axi example_ipbus; do
    bust "$examples/$example.json" -o "$output_dir" -p
    # PDFs need pdflatex. The .tex header names the running bust version,
    # while the goldens keep the version they were generated with.
    diff -r -x '*.pdf' -I 'Generated by bust ' \
        "$examples/$example" "$output_dir/$example"
done
echo "Smoke test passed for bust $expected_version"
